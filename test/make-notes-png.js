const CRC_TABLE = (() => {
  const t = new Int32Array(256);
  for (let n = 0; n < 256; n++) {
    let c = n;
    for (let k = 0; k < 8; k++) c = c & 1 ? 0xedb88320 ^ (c >>> 1) : c >>> 1;
    t[n] = c;
  }
  return t;
})();

function crc32(buf) {
  let c = 0xffffffff;
  for (const b of buf) c = CRC_TABLE[(c ^ b) & 0xff] ^ (c >>> 8);
  return (c ^ 0xffffffff) >>> 0;
}

function chunk(type, data) {
  const len = Buffer.alloc(4);
  len.writeUInt32BE(data.length);
  const body = Buffer.concat([Buffer.from(type, "ascii"), data]);
  const crc = Buffer.alloc(4);
  crc.writeUInt32BE(crc32(body));
  return Buffer.concat([len, body, crc]);
}

/** @param {string[]} lines @returns {Buffer} grayscale PNG */
export function notesPng(lines, { scale = 4, pad = 24, lineGap = 6 } = {}) {
  const glyphW = 6, glyphH = 7; // 5px glyph + 1px letter spacing
  const cols = Math.max(...lines.map((l) => l.length));
  const w = pad * 2 + cols * glyphW * scale;
  const h = pad * 2 + lines.length * (glyphH + lineGap) * scale;

  const px = Buffer.alloc(w * h, 0xff); // white page
  const set = (x, y) => {
    if (x >= 0 && y >= 0 && x < w && y < h) px[y * w + x] = 0x18; // near-black ink
  };

  lines.forEach((line, li) => {
    const baseY = pad + li * (glyphH + lineGap) * scale;
    [...line.toUpperCase()].forEach((ch, ci) => {
      const g = FONT[ch];
      if (!g) return;
      const baseX = pad + ci * glyphW * scale;
      for (let r = 0; r < 7; r++) {
        for (let c = 0; c < 5; c++) {
          if (!(g[r] & (1 << (4 - c)))) continue;
          for (let dy = 0; dy < scale; dy++)
            for (let dx = 0; dx < scale; dx++)
              set(baseX + c * scale + dx, baseY + r * scale + dy);
        }
      }
    });
  });

  // scanlines with filter byte 0
  const raw = Buffer.alloc((w + 1) * h);
  for (let y = 0; y < h; y++) {
    raw[y * (w + 1)] = 0;
    px.copy(raw, y * (w + 1) + 1, y * w, (y + 1) * w);
  }

  const ihdr = Buffer.alloc(13);
  ihdr.writeUInt32BE(w, 0);
  ihdr.writeUInt32BE(h, 4);
  ihdr[8] = 8;  // bit depth
  ihdr[9] = 0;  // grayscale
  ihdr[10] = 0; ihdr[11] = 0; ihdr[12] = 0;

  return Buffer.concat([
    Buffer.from([0x89, 0x50, 0x4e, 0x47, 0x0d, 0x0a, 0x1a, 0x0a]),
    chunk("IHDR", ihdr),
    chunk("IDAT", deflateSync(raw, { level: 9 })),
    chunk("IEND", Buffer.alloc(0)),
  ]);
}

